        <h1 id="introduction">Introduction</h1>
<p>REST API untuk sistem tiket dukungan. Dapatkan token lewat POST /api/v1/login, lalu kirim sebagai Bearer token.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost</code>
</aside>
<pre><code>Dokumentasi ini menjelaskan endpoint REST API HelpDesk Pro.

&lt;aside&gt;Contoh kode ada di area gelap sebelah kanan (atau di dalam konten pada layar kecil). Ganti bahasa lewat tab di kanan atas.&lt;/aside&gt;

**Alur singkat:** panggil &lt;code&gt;POST /api/v1/login&lt;/code&gt; untuk mendapat token, lalu kirim header &lt;code&gt;Authorization: Bearer {token}&lt;/code&gt; pada setiap request lain.</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {YOUR_AUTH_KEY}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Dapatkan token lewat <code>POST /api/v1/login</code>.</p>

